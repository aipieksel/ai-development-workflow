"""Deterministic legacy-checkpoint tests; no workers or host timers are called.

All identities, capability observations and receipts are synthetic test data.
The fixed legacy handoff hashes are deliberately not regenerated by the runtime
under test: renaming a visible mode must not silently rewrite saved artifacts.
"""
import copy
from datetime import datetime, timedelta, timezone
import json
from pathlib import Path
import sys
import unittest

SCRIPTS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SCRIPTS))
import loop_checklist as loop
import xr_checklist as legacy


RUN = "fixture:legacy-loop"
WORKER = "fixture:reviewer-before"
WAIT = {"name": "fixture.wait", "contract": "fixture:wait-capability",
        "minWaitSeconds": 1, "maxWaitSeconds": 60}
TIMER = {"kind": "one-shot", "canCancel": True,
         "contract": "fixture:timer-capability"}


def stamp(seconds=0):
    start = datetime(2026, 1, 1, tzinfo=timezone.utc)
    return (start + timedelta(seconds=seconds)).isoformat().replace("+00:00", "Z")


class LegacyAccountingTests(unittest.TestCase):
    def setUp(self):
        self.path = Path(__file__).parent / "fixtures/legacy-xr-handoff.json"
        self.original_bytes = self.path.read_bytes()
        self.documents = json.loads(self.original_bytes)

    def test_legacy_hash_chain_is_valid_through_both_entry_points_without_rewriting(self):
        before = copy.deepcopy(self.documents)
        report = loop.check_accounting(**self.documents)
        self.assertTrue(report["valid"], report["errors"])
        self.assertTrue(report["readyForFreshReview"])
        self.assertFalse(report["reviewerAcceptanceRecorded"])
        self.assertEqual(report, legacy.check_accounting(**self.documents))
        self.assertEqual(
            loop.canonical_hash(self.documents["review"]),
            "11f92929937f502ffe4b0ddc9e1cce71148080ad71fa799b102db90241877c63",
        )
        self.assertEqual(
            loop.canonical_hash(self.documents["checklist"]),
            "c70f4bee1e5722216339af5d56dc761d05c718a5042dc7f3d4630956d834a7d6",
        )
        self.assertEqual(self.documents, before)
        self.assertEqual(self.path.read_bytes(), self.original_bytes)

    def test_changed_legacy_review_or_checklist_cannot_reuse_old_hashes(self):
        self.documents["review"]["findings"][0]["summary"] = "A different finding."
        report = loop.check_accounting(**self.documents)
        self.assertFalse(report["valid"])
        self.assertIn("checklist reviewHash does not match the exact review", report["errors"])
        self.documents = json.loads(self.original_bytes)
        self.documents["checklist"]["items"][0]["task"] = "A different task."
        report = loop.check_accounting(**self.documents)
        self.assertFalse(report["valid"])
        self.assertIn("execution checklistHash does not match the exact checklist", report["errors"])
        self.assertFalse(report["reviewerAcceptanceRecorded"])


class NoRepairCorroborationTests(unittest.TestCase):
    def setUp(self):
        self.path = Path(__file__).parent / "fixtures/legacy-xr-handoff.json"
        self.original = self.path.read_bytes()
        previous = json.loads(self.original)
        self.review = {**previous["review"], "verdict": "accepted", "findings": []}
        self.checklist = {**previous["checklist"], "reviewHash": loop.canonical_hash(self.review), "items": []}
        self.corroboration = {
            "schema": "ai-development-workflow/loop-corroboration/v1",
            **{key: self.review[key] for key in ("runId", "round", "sourceRevision", "outputRevision")},
            "reviewHash": loop.canonical_hash(self.review), "verifierId": "fixture:independent-verifier",
            "coverage": copy.deepcopy(self.review["coverage"]), "verdict": "confirmed", "findings": [],
            "evidence": ["fixture:independent-source-result-comparison"],
        }
        self.acknowledgement = {
            "schema": "ai-development-workflow/loop-acknowledgement/v1",
            **{key: self.review[key] for key in ("runId", "round", "sourceRevision", "outputRevision")},
            "reviewHash": loop.canonical_hash(self.review), "corroborationHash": loop.canonical_hash(self.corroboration),
            "reviewerId": self.review["reviewerId"], "decision": "accepted", "evidence": ["fixture:reviewer-inspected-corroboration"],
        }

    def check(self):
        return loop.check_accounting(self.review, self.checklist, corroboration=self.corroboration, acknowledgement=self.acknowledgement)

    def test_no_repair_needs_two_actual_declared_contributors_and_reviewer_acknowledgement(self):
        missing = loop.check_accounting(self.review, self.checklist)
        self.assertFalse(missing["valid"])
        self.assertFalse(missing["reviewerAcceptanceRecorded"])
        result = self.check()
        self.assertTrue(result["valid"], result["errors"])
        self.assertTrue(result["reviewerAcceptanceRecorded"])
        self.assertTrue(result["noRepairCorroborationRecorded"])
        self.assertEqual(result["checklistItemCount"], 0)
        self.assertEqual(self.path.read_bytes(), self.original)

    def test_same_identity_stale_revision_or_dropped_coverage_cannot_accept(self):
        original = copy.deepcopy(self.corroboration)
        for mutate in (
            lambda row: row.update(verifierId=self.review["reviewerId"]),
            lambda row: row.update(verifierId=self.checklist["managerId"]),
            lambda row: row.update(outputRevision="fixture:stale-result"),
            lambda row: row["coverage"].pop(),
        ):
            self.corroboration = copy.deepcopy(original)
            mutate(self.corroboration)
            self.acknowledgement["corroborationHash"] = loop.canonical_hash(self.corroboration)
            result = self.check()
            self.assertFalse(result["valid"])
            self.assertFalse(result["reviewerAcceptanceRecorded"])

    def test_manager_cannot_acknowledge_and_acknowledgement_cannot_reuse_changed_report(self):
        self.acknowledgement["reviewerId"] = self.checklist["managerId"]
        self.assertFalse(self.check()["valid"])
        self.acknowledgement["reviewerId"] = self.review["reviewerId"]
        self.corroboration["evidence"].append("fixture:different-countercheck")
        result = self.check()
        self.assertFalse(result["valid"])
        self.assertIn("Reviewer acknowledgement does not cover the exact Verifier corroboration", result["errors"])

    def test_unresolved_corroboration_cannot_be_overridden_by_acceptance(self):
        self.corroboration.update(verdict="changes-required", findings=[{
            "id": "fixture:new-defect", "disposition": "actionable", "summary": "The independent check found an uncovered requirement.",
            "acceptance": "The required target passes its comparison.", "evidence": ["fixture:uncovered-required-target"],
        }])
        self.acknowledgement["corroborationHash"] = loop.canonical_hash(self.corroboration)
        result = self.check()
        self.assertFalse(result["valid"])
        self.assertFalse(result["reviewerAcceptanceRecorded"])
        self.acknowledgement["decision"] = "changes-required"
        result = self.check()
        self.assertTrue(result["valid"], result["errors"])
        self.assertFalse(result["reviewerAcceptanceRecorded"])

    def test_repaired_result_still_requires_fresh_reviewer_after_execution(self):
        documents = json.loads(self.original)
        review, execution = documents["review"], documents["execution"]
        acceptance = {**copy.deepcopy(review), "round": review["round"] + 1, "reviewerId": "fixture:fresh-reviewer",
                      "outputRevision": execution["outputRevision"], "verdict": "accepted", "findings": [],
                      "resolutions": [{"id": row["id"], "status": "resolved", "evidence": ["fixture:current-fix-check"]}
                                      for row in review["findings"] if row["disposition"] == "actionable"]}
        result = loop.check_accounting(**documents, acceptance=acceptance)
        self.assertTrue(result["valid"], result["errors"])
        self.assertTrue(result["reviewerAcceptanceRecorded"])
        for actor in (review["reviewerId"], execution["executorId"], documents["checklist"]["managerId"]):
            acceptance["reviewerId"] = actor
            result = loop.check_accounting(**documents, acceptance=acceptance)
            self.assertFalse(result["valid"])
            self.assertFalse(result["reviewerAcceptanceRecorded"])


class LoopMonitoringTests(unittest.TestCase):
    def step(self, state, kind, *, elapsed=0, **fields):
        """Check the public transition's non-mutating, non-executing boundary."""
        before = copy.deepcopy(state)
        result = loop.monitor_transition(
            state, {"type": kind, "runId": RUN, "now": stamp(elapsed), **fields}
        )
        self.assertEqual(state, before, "A proposed transition must not rewrite its input checkpoint")
        self.assertFalse(result["executesHostActions"])
        return result

    def start(self, mechanism="wait"):
        config = ({"waitTool": WAIT, "nativeTimer": TIMER} if mechanism == "wait" else
                  {"waitUnavailableReason": "fixture:no-wait-tool", "nativeTimer": TIMER})
        return self.step(None, "start", workerId=WORKER, phase="review", **config)

    def arm(self):
        state = self.start("native")["state"]
        return self.step(state, "registered", attempt=state["registrationAttempt"],
                         timerId="fixture:timer-1", receipt="fixture:registration")["state"]

    def test_wait_preference_and_resume_preserve_pending_worker_and_monitor_ownership(self):
        started = self.start()
        state = started["state"]
        self.assertEqual(state["mode"], "wait")
        self.assertEqual(state["schema"], "ai-development-workflow/xr-timer/v1")
        self.assertEqual(state["intervalSeconds"], 300)
        self.assertEqual(state["nextCheckAt"], stamp(300))
        self.assertEqual([row["type"] for row in started["actions"]], ["wait-host"])
        self.assertEqual(started["actions"][0]["seconds"], 60)
        pending = copy.deepcopy(state["activeWait"])
        resumed = self.step(state, "resume", elapsed=10)
        self.assertEqual(resumed, legacy.monitor_transition(
            state, {"type": "resume", "runId": RUN, "now": stamp(10)}
        ))
        held = resumed["state"]
        for name in ("runId", "workerId", "monitorGeneration", "waitAttempt", "activeWait"):
            self.assertEqual(held[name], state[name])
        self.assertEqual([row["type"] for row in resumed["actions"]],
                         ["inspect-current-worker", "reconcile-host-wait"])
        premature = self.step(held, "resumed", workerId=WORKER, workerStatus="running",
                              workerReceipt="fixture:worker-running")
        self.assertEqual(premature["actions"][0]["type"], "report-resume-blocker")
        self.assertEqual(premature["state"]["activeWait"], pending)
        cleaned = self.step(held, "wait-reconciled", **pending, waitStatus="inactive",
                            receipt="fixture:wait-reconciled")["state"]
        continued = self.step(cleaned, "resumed", workerId=WORKER, workerStatus="running",
                              workerReceipt="fixture:worker-running")
        self.assertEqual(continued["state"]["runId"], RUN)
        self.assertEqual(continued["state"]["workerId"], WORKER)
        self.assertEqual(continued["state"]["monitorGeneration"], state["monitorGeneration"])
        self.assertEqual(continued["state"]["waitAttempt"], pending["attempt"] + 1)
        self.assertEqual([row["type"] for row in continued["actions"]],
                         ["continue-current-worker", "wait-host"])

    def test_duplicate_start_rejected_for_wait_and_native_monitor(self):
        for mechanism in ("wait", "native"):
            with self.subTest(mechanism=mechanism):
                state = self.start(mechanism)["state"]
                before = copy.deepcopy(state)
                with self.assertRaisesRegex(ValueError, "never create a duplicate monitor"):
                    self.step(state, "start", workerId=WORKER, phase="review", waitTool=WAIT)
                self.assertEqual(state, before)

    def test_stale_wait_contexts_cannot_complete_worker_or_replace_active_wait(self):
        state = self.start()["state"]
        pending = state["activeWait"]
        for field, value in (("generation", pending["generation"] + 1),
                             ("attempt", pending["attempt"] + 1),
                             ("tool", "fixture:other-tool"), ("workerId", "fixture:other-worker")):
            with self.subTest(field=field):
                context = {**pending, field: value}
                result = self.step(state, "wait-returned", **context,
                                   outcome="worker-completed", receipt="fixture:stale-result",
                                   workerReceipt="fixture:stale-worker-result")
                self.assertEqual(result["state"], state)
                self.assertEqual(result["actions"][0]["type"], "ignore")
        with self.assertRaisesRegex(ValueError, "current generation, attempt, tool"):
            self.step(state, "wait-reconciled", **{**pending, "generation": 0},
                      waitStatus="inactive", receipt="fixture:stale-reconciliation")
        returned = self.step(state, "wait-returned", elapsed=60, **pending,
                             outcome="timeout", receipt="fixture:wait-timeout")
        later = returned["state"]
        self.assertEqual(later["activeWait"]["attempt"], pending["attempt"] + 1)
        duplicate = self.step(later, "wait-returned", elapsed=60, **pending,
                              outcome="timeout", receipt="fixture:duplicate-timeout")
        self.assertEqual(duplicate["state"], later)
        self.assertEqual(duplicate["actions"][0]["type"], "ignore")

    def test_stale_native_registration_and_wake_do_not_rearm_monitor(self):
        state = self.start("native")["state"]
        with self.assertRaisesRegex(ValueError, "stale native registration attempt"):
            self.step(state, "registered", attempt=0, timerId="fixture:old-timer",
                      receipt="fixture:stale-registration")
        state = self.arm()
        unrelated = self.step(state, "wake", elapsed=300, timerId="fixture:old-timer",
                              eventId="fixture:old-wake")
        self.assertEqual(unrelated["state"], state)
        self.assertEqual(unrelated["actions"][0]["type"], "ignore")
        checked = self.step(state, "wake", elapsed=300, timerId="fixture:timer-1",
                            eventId="fixture:wake-1")
        self.assertEqual(checked["actions"], [{"type": "inspect-current-worker", "workerId": WORKER}])
        duplicate = self.step(checked["state"], "wake", elapsed=300,
                              timerId="fixture:timer-1", eventId="fixture:wake-1")
        self.assertEqual(duplicate["state"], checked["state"])
        self.assertEqual(duplicate["actions"][0]["type"], "ignore")
        next_registration = self.step(checked["state"], "checked", elapsed=300,
                                      receipt="fixture:observed-worker")["state"]
        self.assertEqual(next_registration["registrationAttempt"], 2)
        with self.assertRaisesRegex(ValueError, "stale native registration attempt"):
            self.step(next_registration, "registered", elapsed=300, attempt=1,
                      timerId="fixture:timer-1", receipt="fixture:late-registration")

    def test_accepted_and_cancelled_states_require_cleanup_but_never_restart(self):
        for mechanism in ("wait", "native"):
            for phase in ("accepted", "cancelled"):
                with self.subTest(mechanism=mechanism, phase=phase):
                    active = self.start()["state"] if mechanism == "wait" else self.arm()
                    stopped = self.step(active, "stop", phase=phase)
                    state = stopped["state"]
                    self.assertEqual(state["phase"], phase)
                    self.assertEqual(state["runId"], active["runId"])
                    self.assertEqual(state["monitorGeneration"], active["monitorGeneration"])
                    self.assertIsNone(state["workerId"])
                    for kind in ("resume", "resumed", "reconfigure"):
                        result = self.step(state, kind)
                        self.assertEqual(result["state"], state)
                        self.assertEqual(result["actions"][0]["type"], "ignore")
                    if mechanism == "wait":
                        result = self.step(state, "wait-returned", **active["activeWait"],
                                           outcome="timeout", receipt="fixture:terminal-wait-end")
                        self.assertIsNone(result["state"]["activeWait"])
                    else:
                        self.assertEqual(stopped["actions"],
                                         [{"type": "cancel-native", "timerId": active["timerId"]}])
                        result = self.step(state, "cancelled", timerId=active["timerId"],
                                           receipt="fixture:terminal-timer-cancel")
                        self.assertIsNone(result["state"]["timerId"])
                    self.assertEqual(result["state"]["phase"], phase)
                    self.assertEqual(result["state"]["status"], "stopped")
                    self.assertTrue(all(row["type"] == "ignore" for row in result["actions"]))

    def test_historical_native_interval_reconfiguration_requires_cleanup_and_retains_history(self):
        historical = self.arm()
        historical.update(intervalSeconds=600, nextCheckAt=stamp(600), monitorGeneration=4,
                          registrationAttempt=7, registrationSequence=6)
        prior = copy.deepcopy(historical)
        prompt = self.step(historical, "tick", elapsed=300)
        self.assertEqual(prompt["state"], historical)
        self.assertEqual(prompt["actions"][0]["type"], "reconfigure-monitor")
        requested = self.step(historical, "reconfigure", elapsed=300, waitTool=WAIT,
                              receipt="fixture:five-minute-correction")
        state = requested["state"]
        self.assertEqual(state["reconfigurationContext"], {"phase": "review", "workerId": WORKER})
        self.assertEqual(state["timerId"], prior["timerId"])
        self.assertEqual(state["monitorGeneration"], 4)
        self.assertEqual([row["type"] for row in requested["actions"]],
                         ["cancel-native", "inspect-current-worker"])
        confirmation = {"workerId": WORKER, "workerStatus": "running",
                        "workerReceipt": "fixture:worker-still-running",
                        "cleanupReceipt": "fixture:timer-cleanup"}
        premature = self.step(state, "reconfigured", elapsed=300, **confirmation)
        self.assertEqual(premature["actions"][0]["type"], "report-monitoring-blocker")
        self.assertEqual(premature["state"]["timerId"], prior["timerId"])
        cleaned = self.step(state, "cancelled", elapsed=300, timerId=prior["timerId"],
                            receipt="fixture:timer-cleanup")["state"]
        configured = self.step(cleaned, "reconfigured", elapsed=300, **confirmation)
        current = configured["state"]
        self.assertEqual((current["runId"], current["workerId"], current["phase"]),
                         (RUN, WORKER, "review"))
        self.assertEqual((current["intervalSeconds"], current["monitorGeneration"]), (300, 5))
        self.assertEqual(current["registrationSequence"], 7)
        self.assertEqual(current["monitorHistory"][0]["checkpoint"], prior)
        self.assertEqual([row["type"] for row in configured["actions"]], ["wait-host"])
        late = self.step(current, "registered", elapsed=300, attempt=7,
                         timerId=prior["timerId"], receipt="fixture:late-old-timer")
        self.assertEqual(late["state"], current)
        self.assertEqual(late["actions"][0]["type"], "ignore")

    def test_historical_wait_interval_cannot_change_mechanism_until_old_wait_is_reconciled(self):
        historical = self.start()["state"]
        historical.update(intervalSeconds=600, nextCheckAt=stamp(600))
        prior = copy.deepcopy(historical)
        pending = prior["activeWait"]
        requested = self.step(historical, "reconfigure", elapsed=60,
                              waitUnavailableReason="fixture:wait-became-unavailable", nativeTimer=TIMER,
                              receipt="fixture:capability-correction")
        state = requested["state"]
        self.assertEqual(state["activeWait"], pending)
        self.assertFalse(any(row["type"] == "register-native" for row in requested["actions"]))
        confirmation = {"workerId": WORKER, "workerStatus": "running",
                        "workerReceipt": "fixture:worker-still-running",
                        "cleanupReceipt": "fixture:wait-cleanup"}
        premature = self.step(state, "reconfigured", elapsed=60, **confirmation)
        self.assertEqual(premature["actions"][0]["type"], "report-monitoring-blocker")
        cleaned = self.step(state, "wait-reconciled", elapsed=60, **pending,
                            waitStatus="inactive", receipt="fixture:wait-cleanup")["state"]
        configured = self.step(cleaned, "reconfigured", elapsed=60, **confirmation)
        current = configured["state"]
        self.assertEqual((current["runId"], current["workerId"]), (RUN, WORKER))
        self.assertEqual((current["intervalSeconds"], current["monitorGeneration"]), (300, 2))
        self.assertEqual(current["mode"], "native")
        self.assertEqual(current["monitorHistory"][0]["checkpoint"], prior)
        self.assertEqual([row["type"] for row in configured["actions"]], ["register-native"])
        late = self.step(current, "wait-returned", elapsed=60, **pending,
                         outcome="worker-completed", receipt="fixture:late-wait",
                         workerReceipt="fixture:late-worker-result")
        self.assertEqual(late["state"], current)
        self.assertEqual(late["actions"][0]["type"], "ignore")


